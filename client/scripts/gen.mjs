#!/usr/bin/env node
// Compiles the spec's JSON Schemas (../spec/schemas/v0.1) into one standalone ES module,
// src/generated/spec.js, with every schema's validator by its name (`envelope`,
// `sealed/envelope`, `actions/question`, `wire/policy`…) and the words' places in each action
// (sealed/text-paths.json). The module imports nothing and generates no code at run time, so the
// library runs where eval is refused (Workers) as well as in Node.
//
// It is made from the spec checkout next to it at every check, test and build, and never
// committed: the library always reads the schemas of the spec it sits beside.
//
//   node scripts/gen.mjs
//
// The ajv options are the reference verifier's (spec/conformance/lib/obi.mjs, loadSchemas), plus
// the code options standalone output needs. Ajv's two runtime helpers (string length in code
// points, deep equality) are inlined, as the server's scripts/gen-validators.mjs does.

import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const here = dirname(fileURLToPath(import.meta.url));
const SCHEMA_DIR = join(here, "..", "..", "spec", "schemas", "v0.1");
const OUT_DIR = join(here, "..", "src", "generated");
const SCHEMA_BASE = "https://github.com/obi-ai-bot/obi-sphere/raw/main/spec/schemas/v0.1/";

function schemaFiles(dir) {
  return readdirSync(dir).sort().flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? schemaFiles(path) : name.endsWith(".schema.json") ? [path] : [];
  });
}

const ajv = new Ajv2020({
  strict: true,
  strictTypes: false,
  strictRequired: false,
  allErrors: true,
  validateFormats: false,
  code: { source: true, esm: true, lines: true },
});
ajv.addKeyword({ keyword: "x-obi-text", metaSchema: { enum: ["data", "sealed"] } });

// Each schema by its name (its path under v0.1 without `.schema.json`), and an identifier for the
// standalone export.
const names = [];
for (const path of schemaFiles(SCHEMA_DIR)) {
  const schema = JSON.parse(readFileSync(path, "utf8"));
  const file = relative(SCHEMA_DIR, path).split("\\").join("/");
  if (schema.$id !== SCHEMA_BASE + file) throw new Error(`${path}: $id does not match its path`);
  ajv.addSchema(schema);
  names.push({ name: file.replace(/\.schema\.json$/, ""), id: schema.$id });
}
const refs = Object.fromEntries(names.map((n, i) => [`s${i}`, n.id]));
let code = standaloneCode(ajv, refs);

const helpers = {
  ucs2length: `function __ucs2length(str) { let n = 0; for (const _ of str) n++; return n; }`,
  equal: `function __equal(a, b) {
  if (a === b) return true;
  if (a && b && typeof a === "object" && typeof b === "object") {
    if (Array.isArray(a) !== Array.isArray(b)) return false;
    if (Array.isArray(a)) return a.length === b.length && a.every((v, i) => __equal(v, b[i]));
    const ka = Object.keys(a), kb = Object.keys(b);
    return ka.length === kb.length && ka.every((k) => Object.prototype.hasOwnProperty.call(b, k) && __equal(a[k], b[k]));
  }
  return a !== a && b !== b;
}`,
};
const used = new Set();
code = code.replace(/require\("ajv\/dist\/runtime\/(\w+)"\)\.default/g, (_, name) => {
  if (!helpers[name]) throw new Error(`ajv runtime helper ${name} has no inline version`);
  used.add(name);
  return `__${name}`;
});
if (/require\(/.test(code)) throw new Error("the generated code still requires a module");

const textPaths = JSON.parse(readFileSync(join(SCHEMA_DIR, "sealed", "text-paths.json"), "utf8")).paths;
const table = names.map((n, i) => `  ${JSON.stringify(n.name)}: s${i},`).join("\n");

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(join(OUT_DIR, "spec.js"), `// Generated by scripts/gen.mjs from spec/schemas/v0.1. Do not edit; never committed.
/* eslint-disable */
${[...used].sort().map((name) => helpers[name]).join("\n")}
${code}
/** Every schema's validator, by its name under spec/schemas/v0.1. */
export const validators = {
${table}
};
/** Where each action's words are, as JSON Pointers into its body (spec/schemas/v0.1/sealed/text-paths.json). */
export const textPaths = ${JSON.stringify(textPaths)};
`);
writeFileSync(join(OUT_DIR, "spec.d.ts"), `// Generated by scripts/gen.mjs. Do not edit; never committed.
export interface SchemaError {
  instancePath: string;
  message?: string;
  params?: Record<string, unknown>;
}
export interface Validator {
  (data: unknown): boolean;
  errors?: SchemaError[] | null;
}
export declare const validators: {
${names.map((n) => `  ${JSON.stringify(n.name)}: Validator;`).join("\n")}
};
export declare const textPaths: Record<string, string[]>;
`);
console.log(`gen: ${names.length} schemas from ${relative(process.cwd(), SCHEMA_DIR) || "."}`);
